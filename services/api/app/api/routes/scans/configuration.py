from __future__ import annotations

import uuid

from fastapi import APIRouter, Depends, File, HTTPException, UploadFile
from sqlalchemy.orm import Session

from app.api import schemas
from app.api.auth_hints import hints_out
from app.core.db import get_db
from app.core.pinning import url_host
from app.core.target_guard import TargetNotAllowed
from app.models.scan import Scan
from app.scans import credentials, domains, operations, policy, workspace
from app.scans.views import CredentialInput
from app.specs.parser import SpecError, load_spec

from ._shared import SCAN_ROUTER_KWARGS, EditableScanDep, LightScanDep, ScanWriteDep

router = APIRouter(**SCAN_ROUTER_KWARGS)


def _spec_upload_response(scan: Scan, ingested: operations.SpecIngest) -> schemas.SpecUploadOut:
    """The scan every spec route returns, plus what the parse did to it.

    Built from ``ScanOut`` so the two responses can't drift: the report is the
    only addition.
    """
    return schemas.SpecUploadOut(
        **schemas.ScanOut.model_validate(scan).model_dump(),
        spec_report=ingested.report,
    )


@router.post("/{scan_id}/spec", response_model=schemas.SpecUploadOut)
def upload_spec_inline(
    body: schemas.SpecUpload,
    scan: EditableScanDep,
    principal: ScanWriteDep,
    db: Session = Depends(get_db),
) -> schemas.SpecUploadOut:
    try:
        ingested = operations.ingest_spec(db, scan, body.content)
    except SpecError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    workspace.record_audit(
        db,
        principal,
        "scan.spec_uploaded",
        "scan",
        scan.id,
        {"operations": len(ingested.operations)},
    )
    db.commit()
    return _spec_upload_response(scan, ingested)


@router.post(
    "/{scan_id}/spec/file",
    response_model=schemas.SpecUploadOut,
    # Explicit operation id: the multipart body schema in /docs is named
    # Body_<operation_id>, and the autogenerated one was an unreadable
    # snake-case path mash.
    operation_id="uploadSpecFile",
)
async def upload_spec_file(
    scan: EditableScanDep,
    principal: ScanWriteDep,
    file: UploadFile = File(...),
    db: Session = Depends(get_db),
) -> schemas.SpecUploadOut:
    raw = (await file.read()).decode("utf-8", errors="replace")
    try:
        ingested = operations.ingest_spec(db, scan, raw)
    except SpecError as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc
    workspace.record_audit(
        db,
        principal,
        "scan.spec_uploaded",
        "scan",
        scan.id,
        {"operations": len(ingested.operations)},
    )
    db.commit()
    return _spec_upload_response(scan, ingested)


@router.patch("/{scan_id}/operations", response_model=schemas.ScanOut)
def update_operations(
    body: schemas.OperationsUpdate,
    scan: EditableScanDep,
    principal: ScanWriteDep,
    db: Session = Depends(get_db),
) -> Scan:
    """Bulk enable/disable operations so the UI can exclude endpoints from a run."""
    operations.set_operation_selection(
        db, scan, [(o.id, o.enabled) for o in body.operations]
    )
    workspace.record_audit(
        db, principal, "scan.operations_updated", "scan", scan.id
    )
    db.commit()
    return scan


def _guard_credential_urls(
    body: schemas.CredentialCreate | schemas.CredentialUpdate,
) -> None:
    """Reject grant/refresh URLs that point out of egress policy."""
    try:
        policy.guard_credential_urls(
            token_url=body.token_url,
            refresh_url=body.refresh_url,
        )
    except policy.CredentialUrlBlocked as exc:
        raise HTTPException(status_code=422, detail=str(exc)) from exc


@router.get("/{scan_id}/auth-hints", response_model=schemas.AuthHintsOut)
def scan_auth_hints(scan: LightScanDep) -> schemas.AuthHintsOut:
    """How this scan's spec says its API authenticates — the credential form's defaults."""
    if not scan.spec_text:
        raise HTTPException(status_code=409, detail="upload a spec first")
    try:
        # The stored spec was already imported; never fetch a remote $ref again.
        data = load_spec(scan.spec_text, remote_ref_allowlist=[])
    except SpecError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    return hints_out(data)


def _credential_input(
    body: schemas.CredentialCreate | schemas.CredentialUpdate,
) -> CredentialInput:
    """Adapt the validated HTTP body to the service's own input object."""
    return CredentialInput(**body.model_dump())


@router.post(
    "/{scan_id}/credentials", response_model=schemas.CredentialOut, status_code=201
)
def add_credential(
    body: schemas.CredentialCreate,
    scan: EditableScanDep,
    principal: ScanWriteDep,
    db: Session = Depends(get_db),
):
    _guard_credential_urls(body)
    try:
        cred = credentials.add_credential(db, scan, _credential_input(body))
    except ValueError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    workspace.record_audit(
        db,
        principal,
        "credential.added",
        "credential",
        cred.id,
        {"name": cred.name, "role": cred.role, "local_only": cred.local_only},
    )
    db.commit()
    return cred


@router.patch("/{scan_id}/credentials/{cred_id}", response_model=schemas.CredentialOut)
def update_credential(
    cred_id: uuid.UUID,
    body: schemas.CredentialUpdate,
    scan: EditableScanDep,
    principal: ScanWriteDep,
    db: Session = Depends(get_db),
):
    _guard_credential_urls(body)
    try:
        cred = credentials.update_credential(db, scan, cred_id, _credential_input(body))
    except ValueError as exc:
        raise HTTPException(status_code=409, detail=str(exc)) from exc
    if cred is None:
        raise HTTPException(status_code=404, detail="credential not found")
    workspace.record_audit(
        db,
        principal,
        "credential.updated",
        "credential",
        cred.id,
        {"name": cred.name, "role": cred.role},
    )
    db.commit()
    return cred


@router.delete("/{scan_id}/credentials/{cred_id}")
def delete_credential(
    cred_id: uuid.UUID,
    scan: EditableScanDep,
    principal: ScanWriteDep,
    db: Session = Depends(get_db),
) -> dict[str, str]:
    if not credentials.delete_credential(db, scan, cred_id):
        raise HTTPException(status_code=404, detail="credential not found")
    workspace.record_audit(
        db, principal, "credential.deleted", "credential", cred_id
    )
    db.commit()
    return {"status": "deleted"}


@router.get("/{scan_id}/ownership", response_model=schemas.TargetOwnershipOut)
def target_ownership(
    scan: LightScanDep, db: Session = Depends(get_db)
) -> schemas.TargetOwnershipOut:
    """Whether running this scan needs proof the workspace owns its target.

    Answers the run gate's ownership question ahead of the run, so the panel can
    say "verify this domain first" instead of the run being refused. Nothing is
    fetched from the target; the run still proves ownership live.
    """
    try:
        policy.require_target_allowed(scan.target_base_url)
        status = domains.ownership_status(db, scan.tenant_id, scan.target_base_url)
    except TargetNotAllowed as exc:
        return schemas.TargetOwnershipOut(
            host=url_host(scan.target_base_url) or "",
            allowed=False,
            required=False,
            exempt=None,
            domain_id=None,
            verified_at=None,
            last_error=None,
            reason=str(exc),
        )
    record = status.record
    return schemas.TargetOwnershipOut(
        host=status.host,
        allowed=True,
        required=status.exempt is None,
        exempt=status.exempt,
        domain_id=record.id if record else None,
        verified_at=record.verified_at if record else None,
        last_error=record.last_error if record else None,
        reason=None,
    )
